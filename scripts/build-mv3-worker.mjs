import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));

function stripShebang(source) {
  return source.replace(/^#![^\r\n]*(?:\r?\n|$)/, '');
}

async function jsFiles(directory) {
  const result = [];
  for (const entry of await readdir(join(root, directory), { withFileTypes: true })) {
    if (entry.isDirectory()) result.push(...await jsFiles(join(directory, entry.name)));
    else if (entry.isFile() && entry.name.endsWith('.js')) result.push(join(directory, entry.name));
  }
  return result.sort();
}

function removeExportSyntax(source, filename) {
  const names = [...source.matchAll(/^export\s+(?:const|let|var|function|class)\s+([\w$]+)/gm)]
    .map(match => match[1]);
  return {
    source: source.replace(/^export\s+(?=(?:const|let|var|function|class)\s)/gm, ''),
    names,
  };
}

async function buildModuleRegistry() {
  const files = [
    ...(await jsFiles('module')).filter(file => !file.endsWith('/index.js')),
    ...(await jsFiles('setting/plugin')).filter(file =>
      !file.endsWith('/index.js') && !file.endsWith('/function.js')),
  ];
  const blocks = [];

  for (const file of files) {
    const source = await readFile(join(root, file), 'utf8');
    if (/^\s*import\s/m.test(source)) {
      throw new Error(`Worker module bundler does not support imports in ${file}`);
    }
    const transformed = removeExportSyntax(source, file);
    const exports = transformed.names.map(name => `${JSON.stringify(name)}: ${name}`).join(',\n');
    const id = relative(root, file).split('\\').join('/');
    blocks.push(`\n// ${id}\nObject.defineProperty(globalThis.__drrrModules, ${JSON.stringify(id)}, {\n  configurable: true,\n  get() {\n    const module = (() => {\n      "use strict";\n${transformed.source.split('\n').map(line => `      ${line}`).join('\n')}\n      return {${exports}};\n    })();\n    Object.defineProperty(globalThis.__drrrModules, ${JSON.stringify(id)}, {\n      configurable: true,\n      value: module,\n    });\n    return module;\n  },\n});\n`);
  }

  const output = `// Generated by scripts/build-mv3-worker.mjs. Do not edit by hand.\nglobalThis.__drrrModules = Object.create(null);\n${blocks.join('')}`;
  await writeFile(join(root, 'background/worker-modules.js'), output);
}

async function buildLambdaRuntime() {
  let lexer = stripShebang(await readFile(join(root, 'lib/lambda-lexer.mjs'), 'utf8'));
  lexer = lexer.replace(/\nexport\s+\{\s*llexer\s+as\s+lexer\s*\}\s*$/, '\nglobalThis.LambdaLexer = llexer;');

  let parser = stripShebang(await readFile(join(root, 'lib/parse-lambda.mjs'), 'utf8'));
  parser = parser.replace(/^import\s*\{[\s\S]*?\}\s*from\s*["']\.\/lambda-lexer\.mjs["'];\s*/m, '');
  const parserMain = parser.indexOf('\nfunction main(){');
  const parserRemoveTok = parser.indexOf('\nfunction removeTok', parserMain);
  if (parserMain < 0 || parserRemoveTok < 0) throw new Error('Could not locate parser CLI block');
  parser = parser.slice(0, parserMain) + parser.slice(parserRemoveTok);
  parser = parser.replace(/\nexport\s+\{\s*Parser[\s\S]*?\};/, '\n');

  let runner = stripShebang(await readFile(join(root, 'lib/run-lambda.mjs'), 'utf8'));
  runner = runner.replace(/^import\s*\{[\s\S]*?\}\s*from\s*["']\.\/lambda-lexer\.mjs["'];\s*/m, '');
  runner = runner.replace(/^import\s*\{[\s\S]*?\}\s*from\s*["']\.\/parse-lambda\.mjs["'];\s*/m, '');
  runner = runner.replace(/\bDUMP\b/g, 'RUNNER_DUMP');
  const runnerMain = runner.indexOf('\nfunction main(){');
  const runnerExport = runner.indexOf('\nexport { Machine', runnerMain);
  if (runnerMain < 0 || runnerExport < 0) throw new Error('Could not locate lambda runner CLI block');
  runner = runner.slice(0, runnerMain) + runner.slice(runnerExport).replace(/\nexport\s+\{\s*Machine[\s\S]*?\};/, '\n');
  runner += '\nglobalThis.RL = { Machine, compile, execute, interact, insert };\n';

  await writeFile(join(root, 'background/worker-lambda.js'), `// Generated by scripts/build-mv3-worker.mjs. Do not edit by hand.\n(() => {\n"use strict";\n${lexer}\n${parser}\n${runner}\n})();\n`);
}

await buildLambdaRuntime();
await buildModuleRegistry();
console.log('Generated MV3 worker assets.');
